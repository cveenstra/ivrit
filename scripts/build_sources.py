"""Write SOURCES.md from the build outputs (source/rejects.json, source/stats.json, data/)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
D = lambda f: json.load(open(os.path.join(ROOT, 'data', f)))  # noqa: E731
items = D('items.json')['items']
sents = D('sentences.json')['sentences']
course = D('course.json')
script = D('script.json')
rejects = json.load(open(os.path.join(HERE, 'source', 'rejects.json')))
stats = json.load(open(os.path.join(HERE, 'source', 'stats.json')))
byid = {i['id']: i for i in items}

rule = [i for i in items if i.get('tr_src') == 'rule']
out = []
w = out.append
w('# Sources\n')
w('Everything in this course was checked against a source; anything that could not be confirmed was left out. '
  'Course data is adapted from English Wiktionary and English Wikipedia under '
  '[CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/). Pages were fetched with `action=render` in October 2026 '
  'and cached by `scripts/wikt.py`; `scripts/build_data.py` rebuilds every item from that cache.\n')
w('## Words\n')
w(f'{len(items)} words and word forms in {len(course["units"])} units and {sum(len(u["lessons"]) for u in course["units"])} lessons.\n')
w('For each word, `build_data.py` looks up its English Wiktionary page and keeps it only if a Hebrew headword there has a '
  'sense matching the course\'s English gloss. Each comma or semicolon part of the gloss is checked against the senses on its '
  'own, and any part not found is dropped (text in parentheses is explanation, not checked). From that headword it takes:\n')
w('- the pointed spelling (with niqqud) and the unpointed spelling Israelis write (ktiv male), which can add a ו or י;')
w('- the transliteration, converted to the modern form where Wiktionary gives a scholarly one as well;')
w('- the gender, for nouns.\n')
w('Present-tense verb forms come from the conjugation table on each verb\'s Wiktionary page (for צָרִיךְ "need", which '
  'Wiktionary lists as an adjective, from its headword line). Feminine adjectives come from the adjective\'s headword line. '
  'The feminine counting numbers (שָׁלוֹשׁ, חָמֵשׁ…) and זֹאת are listed on Wiktionary only as "feminine of" the masculine word; '
  'they are kept because the masculine word is itself a checked item.\n')
w('### Transliteration of inflected forms\n')
w(f'Most inflected forms have no Wiktionary page of their own, so their transliteration is generated by rule from the pointed '
  f'spelling (`scripts/translit.py`): {len(rule)} of {len(items)} items, marked `tr_src: "rule"` in `data/items.json`. '
  f'Run on the {stats["translit_checked"]} course words that do have a Wiktionary transliteration, the same rules agree with '
  f'Wiktionary on {stats["translit_agree"]} ({100 * stats["translit_agree"] / stats["translit_checked"]:.1f}%), ignoring accent marks and apostrophes. '
  'The ones that differ:\n')
for he, wt, g in stats['translit_mismatch']:
    w(f'- {he}: Wiktionary *{wt}*, rule *{g}*')
import sys
sys.path.insert(0, HERE)
import translit  # noqa: E402
wk = [i for i in items if i.get('form') and i.get('tr_src') == 'wiktionary' and ' ' not in i['he']]
same = [i for i in wk if translit.stress_of(translit.modern(i['tr'])) == translit.form_stress(i['he'])]
w(f'\nStress (the accent mark) on generated forms follows the present-tense and adjective pattern: last syllable, except '
  f'feminine singular forms ending in -et/-at, stressed one syllable earlier (*okhélet*). On the {len(wk)} inflected forms '
  f'whose transliteration does come from Wiktionary, this rule picks the same stressed syllable for {len(same)}.\n')
w('## Letters and vowel points\n')
w(f'{len(script["letters"])} letter forms (22 letters, 5 final forms, and the dot / no-dot pairs בּ ב, כּ כ, פּ פ, שׁ שׂ) and '
  f'{len(script["vowels"])} vowel points. `scripts/build_letters.py` reads names, Hebrew names and modern pronunciation from the '
  'tables in Wikipedia\'s [Hebrew alphabet](https://en.wikipedia.org/wiki/Hebrew_alphabet) article (the letter table and the '
  'Israeli standard transliteration table) and the Israeli rows of the vowel table in [Niqqud](https://en.wikipedia.org/wiki/Niqqud), '
  'and fails if they disagree with what the course teaches. Example words for each letter are the ones in the Israeli '
  'transliteration table. ח is taught as *kh*: the Academy of the Hebrew Language writes it *ẖ*, but it sounds the same as כ today. '
  'ג׳ ז׳ צ׳ (loanword sounds) are not taught.\n')
w('Syllable and word readings in the Letters course are built by rule from each letter\'s and vowel\'s sound, to show how '
  'the script works; real words in those lessons are course words written only with letters already learned.\n')
w('## Tracing\n')
w(f'{script and len(json.load(open(os.path.join(ROOT, "data", "tracing.json")))["shapes"])} stroke guides in `data/tracing.json`, '
  'drawn by hand for this app as simplified block-print shapes. They follow common conventions for writing print Hebrew by hand '
  '(top bars first and left to right, uprights top to bottom, bases last), but there is no single official stroke order and '
  'they are **not** taken from a dataset. Cursive (ktav yad) is not included: a guide that teaches it well would need a '
  'proper source, and a rough one would teach the wrong shapes.\n')
w('## Sentences\n')
att = [s for s in sents if s['kind'] == 'attested']
comp = [s for s in sents if s['kind'] == 'composed']
w(f'{len(sents)} sentences.\n')
w(f'**Quoted ({len(att)})**: usage examples on the Wiktionary page of one of the course words, with Wiktionary\'s transliteration '
  'and translation. Only short, pointed, complete sentences are used.\n')
for s in att:
    w(f'- {s["he"]} *{s["tr"]}* "{s["en"]}" (from `{s["src"]}`)')
w(f'\n**Composed for this course ({len(comp)})**: built from checked words in simple present-tense patterns (subject + verb + object, '
  'subject + adjective with no "is", noun + adjective, question word + this). Each word\'s spelling and transliteration is '
  'Wiktionary\'s; the sentence as a whole and its English are this course\'s, so these are the ones worth checking with a '
  'native speaker.\n')
for s in comp:
    w(f'- {s["he"]} *{s["tr"]}* "{s["en"]}"')
w('\n## Left out\n')
w('Words that could not be confirmed and are not in the course:\n')
for r in rejects:
    if not r.get('kept') and not r['id'].startswith('c-'):
        w(f'- {r["title"]} ({r["id"]}): {r["why"]}')
w('\nComposed sentences dropped because a word in them was left out:\n')
for r in rejects:
    if r['id'].startswith('c-'):
        w(f'- "{r["title"]}": {r["why"]}')
w('\nWords kept, with part of the planned English dropped because Wiktionary does not give that sense:\n')
for r in rejects:
    if r.get('kept'):
        w(f'- {r["title"]} ({r["id"]}): {r["why"].replace("kept item; ", "")}')
w('\nRemoved from the candidate list after checking: the prefixes מ־ "from" and שׁ־ "that" (they attach to words and change '
  'their niqqud); אֶל "to" (its page leads with "god"); אֲנָשִׁים people, יְלָדִים children, הוֹרִים parents and גַּרְבַּיִם socks (their pages '
  'only say "plural of"); מִצְטַעֵר sorry (listed only as a verb form); כְּלוּם (Wiktionary\'s sense is "anything", '
  'not "nothing" on its own).\n')
w('## Audio\n')
w('The app records no audio. 🔊 buttons and listening questions use the browser\'s own Hebrew text-to-speech voice when '
  'the device has one, and are hidden otherwise.\n')
open(os.path.join(ROOT, 'SOURCES.md'), 'w').write('\n'.join(out) + '\n')
print('SOURCES.md', len(out), 'lines')
